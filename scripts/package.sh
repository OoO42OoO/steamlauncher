#!/usr/bin/env bash
#
# scripts/package.sh — automated distributable build for steam-client.
#
# Performs everything needed to go from a fresh clone to .AppImage / .deb /
# Windows .zip in apps/desktop/dist/:
#
#   1. Download + verify DepotDownloader v3.4.0 binaries for Linux and
#      Windows into vendor/{linux-x64,win-x64}/. Skipped if already present.
#   2. Pre-cache the Electron Windows release zip into ~/.cache/electron/
#      so cross-builds don't fail with a GitHub timeout in the middle of
#      a 5-minute build (we hit this twice manually).
#   3. Wipe apps/desktop/dist/ for a clean build.
#   4. Run electron-builder for the requested target(s).
#   5. Print artifact summary with sizes.
#
# Usage:
#   scripts/package.sh              # builds linux + windows
#   scripts/package.sh linux        # AppImage + .deb only
#   scripts/package.sh win          # Windows .zip only
#   scripts/package.sh all          # explicit form of default
#
# Notes:
# - Windows code-signing is intentionally NOT performed (no cert).
# - Windows NSIS installer is NOT produced — that target needs `wine` on
#   the build host and we ship a portable .zip instead.
# - macOS target is NOT supported by design.
#
# Exit codes: 0 success, non-zero on any check failure.
set -euo pipefail

# ── locate repo root regardless of where the script is invoked from ──
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
cd "${REPO_ROOT}"

TARGETS="${1:-all}"
case "${TARGETS}" in
  linux|win|all) ;;
  *) echo "Usage: $0 [linux|win|all]" >&2; exit 2 ;;
esac

# ── pinned versions and checksums ──────────────────────────────────────
DD_VERSION="3.4.0"
DD_BASE_URL="https://github.com/SteamRE/DepotDownloader/releases/download/DepotDownloader_${DD_VERSION}"
# Computed from the official zips:
#   curl -fL <url> | sha256sum
DD_LINUX_SHA="a999dec66b4850fc961bd50366696d23c2d0fad7b18790e6a5647b2f19097a53"
DD_WIN_SHA="41c9e9f0df54b3ad02e67a11726756e5c73283bd7c2e1b04acfa5ae4c2ed3767"

# gbe_fork (LGPLv3) — Goldberg Steam Emulator fork by Detanup01. We migrated
# off Mr_Goldberg/Goldberg v0.2.5 (Apr 2026) because the original tag
# silently fails to load on any game compiled against Steam SDK > 1.51:
# it ignores the missing per-game interface map and the game falls back
# to RestartAppIfNecessary() → bounces to Steam. gbe_fork supports modern
# SDKs but requires `steam_interfaces.txt` per DLL — generated by the
# tools/generate_interfaces_*.exe binaries we also bundle from the same
# release. The DRM patcher computes the file at patch time, since the
# interface set is per-game (varies by SDK version the publisher linked).
GBE_FORK_TAG="release-2026_05_19"
GBE_FORK_URL="https://github.com/Detanup01/gbe_fork/releases/download/${GBE_FORK_TAG}/emu-win-release.7z"
GBE_FORK_SHA="7be0ead31fb2d47747cc4c269a2e2f6c19ad393b238bf7ab56149944fc8af5bb"
# Pinned SHA-256 of the file as it lives in the 7z (verified post-extract).
# Recompute when bumping GBE_FORK_TAG.
GBE_FORK_LOADER_SHA="2b6a295b391978d3ef4215b0e403462999bb8526392c67ed4d9eea6445520f82"

# Steamless CLI (CC BY-NC-ND 4.0) — strips the SteamStub DRM wrapper from
# game executables so they boot without a running Steam process. License is
# non-commercial / no-derivatives; we ship the binary unmodified.
STEAMLESS_VERSION="3.1.0.5"
STEAMLESS_URL="https://github.com/atom0s/Steamless/releases/download/v${STEAMLESS_VERSION}/Steamless.v${STEAMLESS_VERSION}.-.by.atom0s.zip"
STEAMLESS_SHA="e3e2d22e098ff3fb359b2876aa2bed9596f0501e6ff588cbffae90a76d2dc4f5"

# Read the Electron version pinned in apps/desktop/package.json so we
# stay in sync with whatever electron-builder will rebuild for.
ELECTRON_VERSION="$(node -p "require('./apps/desktop/package.json').devDependencies.electron")"
# strip a leading ^ or ~ if someone changes the pin to a range later
ELECTRON_VERSION="${ELECTRON_VERSION#^}"
ELECTRON_VERSION="${ELECTRON_VERSION#~}"

# ── helpers ─────────────────────────────────────────────────────────────
say()  { printf '\n\033[1;36m▶ %s\033[0m\n' "$*"; }
ok()   { printf '  \033[1;32m✓\033[0m %s\n' "$*"; }
warn() { printf '  \033[1;33m!\033[0m %s\n' "$*"; }
die()  { printf '\n\033[1;31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "missing required command: $1"
}

# ── Step 1. DepotDownloader binaries ────────────────────────────────────
ensure_dd() {
  local platform="$1"     # linux-x64 | win-x64
  local archive="$2"      # GitHub asset name
  local sha="$3"          # expected sha256 of the archive
  local exe_name="$4"     # binary name inside the archive

  local target="vendor/${platform}/${exe_name}"
  if [[ -f "${target}" ]]; then
    ok "DepotDownloader for ${platform} already present"
    return 0
  fi

  say "Downloading DepotDownloader for ${platform}…"
  mkdir -p "vendor/${platform}"
  local tmp
  tmp="$(mktemp --tmpdir "dd-${platform}-XXXXXX.zip")"
  trap 'rm -f "${tmp}"' EXIT
  curl -fSL --retry 3 --retry-delay 5 --max-time 240 \
    -o "${tmp}" "${DD_BASE_URL}/${archive}"

  echo "${sha}  ${tmp}" | sha256sum -c - >/dev/null \
    || die "checksum mismatch for ${archive} — release tampered, or pin in script is stale"
  ok "checksum verified"

  unzip -o -q "${tmp}" -d "vendor/${platform}/"
  rm -f "${tmp}"
  trap - EXIT

  if [[ "${platform}" == "linux-x64" ]]; then
    chmod +x "vendor/${platform}/DepotDownloader"
  fi
  ok "extracted to vendor/${platform}/"
}

# ── Step 1b. gbe_fork Steam Emulator ────────────────────────────────────
# The upstream release ships a single 7z carrying:
#   - regular/{x86,x64}/steam_api{,64}.dll    single-DLL emulator (no steamclient dep)
#   - experimental/x64/steamclient64.dll       optional, bundled just-in-case
#   - tools/generate_interfaces/*.exe          steam_interfaces.txt generator
#   - steam_settings.EXAMPLE/                  reference configs (ignored — we ship curated ones in git)
#
# We pick only those files and drop them into vendor/win-x64/gbe_fork/. The
# curated steam_settings/configs.{user,main}.ini live under git so a
# malicious upstream release can't rewrite our network/identity defaults.
ensure_gbe_fork() {
  local dest_dir="vendor/win-x64/gbe_fork"
  local marker="${dest_dir}/steam_api64.dll"
  if [[ -f "${marker}" ]] \
     && [[ -f "${dest_dir}/tools/generate_interfaces_x64.exe" ]] \
     && [[ -f "${dest_dir}/steamclient_loader_x64.exe" ]]; then
    ok "gbe_fork DLLs + tools + loader already present"
    return 0
  fi

  require_cmd 7z

  say "Downloading gbe_fork ${GBE_FORK_TAG}…"
  mkdir -p "${dest_dir}/tools" "${dest_dir}/experimental" "${dest_dir}/steam_settings"
  local tmp
  tmp="$(mktemp --tmpdir "gbe-fork-XXXXXX.7z")"
  trap 'rm -f "${tmp}"' EXIT
  curl -fSL --retry 3 --retry-delay 5 --max-time 240 \
    -o "${tmp}" "${GBE_FORK_URL}"

  echo "${GBE_FORK_SHA}  ${tmp}" | sha256sum -c - >/dev/null \
    || die "checksum mismatch for gbe_fork — release tampered, or pin in script is stale"
  ok "checksum verified"

  local stage
  stage="$(mktemp -d --tmpdir "gbe-fork-stage-XXXXXX")"
  trap 'rm -rf "${tmp}" "${stage}"' EXIT
  7z x -y -o"${stage}" "${tmp}" \
    "release/regular/x64/steam_api64.dll" \
    "release/regular/x86/steam_api.dll" \
    "release/experimental/x64/steamclient64.dll" \
    "release/steamclient_experimental/steamclient_loader_x64.exe" \
    "release/tools/generate_interfaces/generate_interfaces_x64.exe" \
    "release/tools/generate_interfaces/generate_interfaces_x86.exe" \
    "release/tools/generate_interfaces/README.generate_interfaces.md" \
    >/dev/null
  cp "${stage}/release/regular/x64/steam_api64.dll" "${dest_dir}/steam_api64.dll"
  cp "${stage}/release/regular/x86/steam_api.dll"   "${dest_dir}/steam_api.dll"
  cp "${stage}/release/experimental/x64/steamclient64.dll" "${dest_dir}/experimental/steamclient64.dll"
  cp "${stage}/release/steamclient_experimental/steamclient_loader_x64.exe" "${dest_dir}/steamclient_loader_x64.exe"
  cp "${stage}/release/tools/generate_interfaces/generate_interfaces_x64.exe" "${dest_dir}/tools/generate_interfaces_x64.exe"
  cp "${stage}/release/tools/generate_interfaces/generate_interfaces_x86.exe" "${dest_dir}/tools/generate_interfaces_x86.exe"
  cp "${stage}/release/tools/generate_interfaces/README.generate_interfaces.md" "${dest_dir}/tools/README.generate_interfaces.md"

  # ColdClientLoader needs a SteamAPI-faithful host process. Pin the loader
  # SHA-256 separately from the archive SHA — the archive checksum already
  # covers the whole release, but an explicit per-file pin gives a clear
  # diagnostic when the upstream sub-asset is replaced and the regression
  # is the loader specifically.
  echo "${GBE_FORK_LOADER_SHA}  ${dest_dir}/steamclient_loader_x64.exe" \
    | sha256sum -c - >/dev/null \
    || die "checksum mismatch for steamclient_loader_x64.exe — upstream changed, update GBE_FORK_LOADER_SHA"
  ok "loader checksum verified"

  rm -f "${tmp}"
  rm -rf "${stage}"
  trap - EXIT
  ok "extracted to ${dest_dir}/"
}

# ── Step 1c. Steamless CLI ──────────────────────────────────────────────
# Ships as a self-contained .NET Framework 4.6.2 binary set; we copy the
# whole release (CLI + GUI + Plugins/) since the unpackers live in
# Plugins/ and the CLI side-loads them by filename at runtime.
ensure_steamless() {
  local dest_dir="vendor/win-x64/steamless"
  local marker="${dest_dir}/Steamless.CLI.exe"
  if [[ -f "${marker}" ]]; then
    ok "Steamless already present"
    return 0
  fi

  say "Downloading Steamless CLI v${STEAMLESS_VERSION}…"
  mkdir -p "${dest_dir}"
  local tmp
  tmp="$(mktemp --tmpdir "steamless-XXXXXX.zip")"
  trap 'rm -f "${tmp}"' EXIT
  curl -fSL --retry 3 --retry-delay 5 --max-time 240 \
    -o "${tmp}" "${STEAMLESS_URL}"

  echo "${STEAMLESS_SHA}  ${tmp}" | sha256sum -c - >/dev/null \
    || die "checksum mismatch for Steamless — release tampered, or pin in script is stale"
  ok "checksum verified"

  unzip -o -q "${tmp}" -d "${dest_dir}/"
  rm -f "${tmp}"
  trap - EXIT
  ok "extracted to ${dest_dir}/"
}

# ── Step 2. Pre-cache Electron Windows zip ─────────────────────────────
# `electron-builder` calls `app-builder` (Go binary) to fetch electron and
# stream-extract it. We've twice seen GitHub return RST mid-download on
# the win32 zip, killing the whole build. Pre-fetching to ~/.cache/electron/
# (the location @electron/get reads from) lets the build skip the network.
precache_electron_win() {
  local cache_dir="${HOME}/.cache/electron"
  local zip_name="electron-v${ELECTRON_VERSION}-win32-x64.zip"
  local zip_path="${cache_dir}/${zip_name}"

  if [[ -f "${zip_path}" ]]; then
    ok "${zip_name} already cached"
    return 0
  fi

  say "Pre-caching ${zip_name} for offline-stable Windows build…"
  mkdir -p "${cache_dir}"
  curl -fSL --retry 3 --retry-delay 5 --max-time 600 \
    -o "${zip_path}" \
    "https://github.com/electron/electron/releases/download/v${ELECTRON_VERSION}/${zip_name}"

  # SHASUMS file lets @electron/get verify our cached copy. Best-effort —
  # if it fails we still proceed; @electron/get will refetch only the SHASUMS.
  curl -fSL --retry 3 --retry-delay 5 --max-time 60 \
    -o "${cache_dir}/SHASUMS256.txt-${ELECTRON_VERSION}" \
    "https://github.com/electron/electron/releases/download/v${ELECTRON_VERSION}/SHASUMS256.txt" \
    || warn "could not fetch SHASUMS256.txt — build may re-download it"
  ok "cached"
}

# ── Step 3. Sanity checks ──────────────────────────────────────────────
require_cmd curl
require_cmd unzip
require_cmd sha256sum
require_cmd node
require_cmd pnpm

if [[ ! -d node_modules ]]; then
  say "node_modules missing — running pnpm install"
  pnpm install
fi

# ── Step 4. Run the pipeline ───────────────────────────────────────────
say "Target: ${TARGETS} (Electron ${ELECTRON_VERSION})"

ensure_dd "linux-x64" "DepotDownloader-linux-x64.zip"   "${DD_LINUX_SHA}" "DepotDownloader"
ensure_dd "win-x64"   "DepotDownloader-windows-x64.zip" "${DD_WIN_SHA}"   "DepotDownloader.exe"

# gbe_fork + Steamless are Windows-only payloads. They live under
# vendor/win-x64/ regardless of the target — keeps the resolver in
# drm-patcher.ts platform-agnostic and lets a Linux client patching a
# downloaded Windows depot still find the DLLs.
if [[ "${TARGETS}" != "linux" ]]; then
  ensure_gbe_fork
  ensure_steamless
fi

if [[ "${TARGETS}" != "linux" ]]; then
  precache_electron_win
fi

say "Cleaning previous build output"
rm -rf apps/desktop/dist
ok "removed apps/desktop/dist"

say "Building distributables"
case "${TARGETS}" in
  linux) pnpm --filter @steam-client/desktop run package:linux ;;
  win)   pnpm --filter @steam-client/desktop run package:win   ;;
  all)   pnpm --filter @steam-client/desktop run package:all   ;;
esac

# ── Step 5. Summary ────────────────────────────────────────────────────
say "Artifacts in apps/desktop/dist/"
# List only files (not unpacked dirs / debug yml) and show human sizes.
find apps/desktop/dist -maxdepth 1 -type f \
  ! -name 'builder-debug.yml' \
  ! -name '*.blockmap' \
  -printf '%f|%s\n' | sort | while IFS='|' read -r name size; do
    # Pretty-print size with `numfmt` if available, else raw bytes.
    if command -v numfmt >/dev/null 2>&1; then
      hsize="$(numfmt --to=iec --suffix=B "${size}")"
    else
      hsize="${size}B"
    fi
    printf '  \033[1;32m✓\033[0m %s  (%s)\n' "${name}" "${hsize}"
  done

say "Done."
